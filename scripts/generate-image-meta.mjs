// Generates the real pixel dimensions of every portfolio photo
// (src/lib/portfolio-image-dims.ts), so the masonry gallery can reserve each
// photo's true aspect ratio before it loads — no layout jump, and no cropping of
// landscape shots.
//
// Re-run whenever photos in public/images are added, replaced or removed:
//   npm run images:meta
// `--check` exits non-zero if the committed file is out of date (CI-friendly).

import fs from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import sharp from "sharp"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const portfolioDir = path.join(root, "public", "images", "portfolio")
const target = path.join(root, "src", "lib", "portfolio-image-dims.ts")
const check = process.argv.includes("--check")

sharp.cache(false)

async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true })
  const files = await Promise.all(
    entries.map((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]))
  )
  return files.flat().filter((f) => /\.(jpe?g|png|webp|avif)$/i.test(f))
}

const files = (await walk(portfolioDir)).sort()
const dims = {}

// Small pool so we don't open hundreds of 6MP JPEGs at once.
const queue = [...files]
await Promise.all(
  Array.from({ length: 6 }, async () => {
    while (queue.length) {
      const file = queue.shift()
      const meta = await sharp(file).metadata()
      // EXIF orientations 5-8 are rotated a quarter turn: browsers display them swapped.
      const swap = (meta.orientation ?? 1) >= 5
      const src = "/" + path.relative(path.join(root, "public"), file).split(path.sep).join("/")
      dims[src] = { width: swap ? meta.height : meta.width, height: swap ? meta.width : meta.height }
    }
  })
)

const sorted = Object.fromEntries(Object.entries(dims).sort(([a], [b]) => (a < b ? -1 : 1)))
const content = [
  "// Generated by scripts/generate-image-meta.mjs (npm run images:meta) — do not edit by hand.",
  "// Real pixel dimensions for every portfolio photo, so the masonry gallery can",
  "// size each image by its actual aspect ratio instead of forcing a fixed box",
  "// (which crops landscape shots badly).",
  `export const portfolioImageDims: Record<string, { width: number; height: number }> = ${JSON.stringify(sorted, null, 2)}`,
  "",
].join("\n")

const current = await fs.readFile(target, "utf8").catch(() => null)
if (current === content) {
  console.log("up to date   src/lib/portfolio-image-dims.ts")
} else if (check) {
  console.log("OUT OF DATE  src/lib/portfolio-image-dims.ts")
  process.exit(1)
} else {
  await fs.writeFile(target, content)
  console.log("written      src/lib/portfolio-image-dims.ts")
}
console.log(`\n${files.length} portfolio photos measured`)
